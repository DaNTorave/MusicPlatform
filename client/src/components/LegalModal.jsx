import React from 'react';
import closeIcon from '../assets/close-icon.svg';
import '../styles/LegalModal.css';

export default function LegalModal({ isOpen, onClose, initialDoc = 'privacy' }) {
  const [activeDoc, setActiveDoc] = React.useState(initialDoc);

  React.useEffect(() => {
    if (initialDoc) {
      setActiveDoc(initialDoc);
    }
  }, [initialDoc, isOpen]);

  if (!isOpen) return null;

  return (
    <div
      className="legal-modal-background"
      onClick={(e) => e.target === e.currentTarget && onClose()}
    >
      <div className="legal-modal-window">
        <div className="legal-modal-top-buttons">
          <button
            type="button"
            className={`legal-modal-top-button ${activeDoc === 'privacy' ? 'legal-modal-active' : ''}`}
            onClick={() => setActiveDoc('privacy')}
          >
            Политика ПДн (152-ФЗ)
          </button>
          <button
            type="button"
            className={`legal-modal-top-button ${activeDoc === 'terms' ? 'legal-modal-active' : ''}`}
            onClick={() => setActiveDoc('terms')}
          >
            Соглашение
          </button>
          <button
            type="button"
            className={`legal-modal-top-button ${activeDoc === 'copyright' ? 'legal-modal-active' : ''}`}
            onClick={() => setActiveDoc('copyright')}
          >
            Правообладателям
          </button>
          <button
            type="button"
            className="legal-modal-close-button"
            onClick={onClose}
            title="Закрыть"
          >
            <img src={closeIcon} alt="Закрыть" />
          </button>
        </div>

        <div className="legal-modal-content">
          {activeDoc === 'privacy' && (
            <div className="legal-doc-section">
              <h2>Политика обработки персональных данных</h2>
              <p className="legal-doc-meta">
                Редакция в соответствии с Федеральным законом РФ от 27.07.2006 № 152-ФЗ «О персональных данных»
              </p>

              <h3>1. Общие положения</h3>
              <p>
                Настоящая Политика определяет порядок обработки и защиты персональных данных пользователей закрытой информационной площадки Music Platform (далее – Платформа). Платформа является некоммерческим закрытым сообществом с ограниченным кругом участников, доступ к которому предоставляется исключительно после предварительной модерации заявки администратором.
              </p>

              <h3>2. Состав обрабатываемых данных</h3>
              <p>
                При регистрации и использовании Платформы обрабатываются следующие минимально необходимые данные: уникальный логин, адрес электронной почты (email), отображаемый никнейм, загружаемый аватар, сведения о музыкальных предпочтениях, а также технические данные сессии (токен авторизации в localStorage браузера).
              </p>

              <h3>3. Цели и правовые основания обработки</h3>
              <p>
                Обработка осуществляется на основании добровольного согласия субъекта персональных данных (ст. 6 ч. 1 п. 1 152-ФЗ) исключительно для идентификации участника закрытого сообщества, рассмотрения заявки на доступ, обеспечения работоспособности личного кабинета и персонализации аудиопотока.
              </p>

              <h3>4. Хранение, защита и удаление данных</h3>
              <p>
                Базы данных Платформы размещаются на серверах на территории Российской Федерации (ч. 5 ст. 18 152-ФЗ). Пароли хранятся исключительно в необратимом криптографически хешированном виде. В случае отклонения заявки на регистрацию администратором все персональные данные заявителя незамедлительно и безвозвратно удаляются из базы данных и файлового хранилища. Пользователь вправе в любой момент отозвать согласие и потребовать удаления учетной записи по адресу: <strong>admin@musicplatform.ru</strong>.
              </p>
            </div>
          )}

          {activeDoc === 'terms' && (
            <div className="legal-doc-section">
              <h2>Пользовательское соглашение закрытого клуба</h2>
              <p className="legal-doc-meta">
                Регулируется законодательством Российской Федерации (ГК РФ, 149-ФЗ, 436-ФЗ)
              </p>

              <h3>1. Статус площадки</h3>
              <p>
                Music Platform является закрытым некоммерческим информационным ресурсом для личного и ознакомительного использования узким кругом одобренных участников. Доступ третьих лиц и публичное индексирование материалов закрыты.
              </p>

              <h3>2. Регистрация и модерация доступа</h3>
              <p>
                Регистрация осуществляется путем подачи заявки с указанием уникального логина и электронной почты. Администрация вправе одобрить или отклонить любую заявку без объяснения причин. При отклонении заявки учетная запись удаляется. Передача учетных данных третьим лицам запрещена.
              </p>

              <h3>3. Обязанности пользователя при загрузке материалов</h3>
              <p>
                Загружая аудиозаписи, обложки и иные материалы, пользователь гарантирует, что не нарушает законодательство РФ, включая запрет на распространение экстремистских материалов, пропаганды наркотических средств, призывов к противоправным действиям, а также соблюдает требования Федерального закона № 436-ФЗ (обязательная маркировка контента, содержащего нецензурную брань или информацию 18+).
              </p>

              <h3>4. Ограничение ответственности</h3>
              <p>
                Платформа функционирует как информационный посредник (ст. 1253.1 ГК РФ). Вся ответственность за правомерность размещения материалов возлагается на пользователя, загрузившего соответствующий файл.
              </p>
            </div>
          )}

          {activeDoc === 'copyright' && (
            <div className="legal-doc-section">
              <h2>Информация для правообладателей (ст. 1253.1 ГК РФ)</h2>
              <p className="legal-doc-meta">
                Порядок рассмотрения обращений о нарушении интеллектуальных прав
              </p>

              <h3>1. Статус информационного посредника</h3>
              <p>
                Администрация Платформы не осуществляет коммерческое распространение фонограмм, не извлекает прибыль из доступа к аудиоматериалам и действует в статусе информационного посредника в соответствии со статьей 1253.1 Гражданского кодекса Российской Федерации.
              </p>

              <h3>2. Премодерация и удаление спорного контента</h3>
              <p>
                Все материалы, загружаемые участниками закрытого сообщества, проходят предварительную проверку модераторами. Если вы являетесь правообладателем исключительных прав на произведение или фонограмму и полагаете, что ваши права нарушены, направьте обращение на электронную почту: <strong>admin@musicplatform.ru</strong>.
              </p>

              <h3>3. Требования к обращению правообладателя</h3>
              <p>
                Для оперативного удаления материала в течение 24 часов в обращении необходимо указать: наименование правообладателя, документы, подтверждающие исключительные права, точное название произведения/исполнителя и контактные данные для обратной связи. После проверки спорный материал и связанные с ним файлы безвозвратно удаляются с сервера.
              </p>
            </div>
          )}
        </div>
      </div>
    </div>
  );
}